def _pill(kind: str) -> str:
    return f'<span class="pill {escape(kind)}">{escape(kind.upper())}</span>'


def report_html(run: Run, show_values: bool = False) -> str:
    s = run.stats()
    t = run.table
    e = escape
    name = Path(t.source).name
    h: list[str] = [
        "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>",
        "<meta name='viewport' content='width=device-width,initial-scale=1'>",
        f"<title>Mapping report · {e(name)}</title><style>{_CSS}</style></head><body><main>",
        "<header><p class='kicker'>Onboarding mapping report</p>",
        f"<h1>{e(name)} → {e(run.schema.name)}</h1>",
        f"<p class='meta'>{s['rows_in']} rows × {s['columns_in']} columns · {e(t.encoding)}"
        + (f" · delimiter <code>{e(repr(t.delimiter))}</code>" if t.delimiter else "")
        + f" · header on row {t.header_row} · as of {run.as_of.isoformat()} · onboarding-mapper {__version__}"
        + ("" if show_values else " · personal values masked")
        + "</p>",
    ]
    if t.notes:
        h.append("<ul class='notes'>" + "".join(f"<li>{e(n)}</li>" for n in t.notes) + "</ul>")
    h.append("</header><section class='tiles'>")
    for cls, num, label in [
        ("ok", s["records_ready"], "records ready to import"),
        ("err" if s["records_held"] else "", s["records_held"], "records held"),
        ("ok", s["fields_auto"], "fields mapped automatically"),
        ("warn" if s["fields_review"] else "", s["fields_review"], "mappings to confirm"),
        ("warn" if s["review_items"] else "", s["review_items"], "items in the review queue"),
        ("", s["cells_normalised"], f"of {s['cells_mapped']} cells normalised"),
    ]:
        h.append(f"<div class='tile {cls}'><b>{num}</b><span>{e(label)}</span></div>")
    h.append("</section>")

    # Mapping table
    h.append(
        "<h2>Mapping</h2><div class='card'><table><thead><tr><th>Target field</th><th>Source column</th><th>Status</th><th>Confidence</th><th>Why</th></tr></thead><tbody>"
    )
    for m in run.mappings.values():
        src = e(m.source) if m.source else "<span class='why'>—</span>"
        if m.method == "split_full_name":
            src += f" <span class='why'>split · {e(m.options.get('part', ''))} name</span>"
        elif m.method == "currency_from_amount":
            src += " <span class='why'>currency read from amounts</span>"
        conf = ""
        if m.source:
            conf = f"<div class='conf'><i style='width:{int(m.confidence * 70)}px'></i><span>{m.confidence:.2f}</span></div>"
        opts = []
        if m.options.get("date_order") and m.source:
            opts.append("dates read " + ("day-first" if m.options["date_order"] == "dmy" else "month-first"))
        if m.options.get("number_style") and m.source:
            opts.append("decimal " + ("comma" if m.options["number_style"] == "eu" else "point"))
        why = "; ".join(m.reasons + opts)
        h.append(
            f"<tr><td><code>{e(m.field)}</code></td><td>{src}</td><td>{_pill(m.status)}</td><td>{conf}</td><td class='why'>{e(why)}</td></tr>"
        )
    h.append("</tbody></table></div>")

    if run.proposal.sensitive or run.proposal.unused:
        h.append(
            "<h2>Columns not imported</h2><div class='card'><table><thead><tr><th>Source column</th><th>Why</th></tr></thead><tbody>"
        )
        for x in run.proposal.sensitive:
            h.append(
                f"<tr><td>{e(x['source'])} {_pill('error')}</td><td>Held back: looks like {e(x['label'])} ({e(x['reason'])}). Not read into any output.</td></tr>"
            )
        for x in run.proposal.unused:
            h.append(f"<tr><td>{e(x['source'])}</td><td class='why'>{e(x['reason'])}</td></tr>")
        h.append("</tbody></table></div>")

    # Before / after
    active = [m for m in run.mappings.values() if m.active and m.column is not None]
    if active and run.result.records:
        sample = run.result.ready[:4] or list(range(min(4, len(run.result.records))))
        h.append("<h2>Before and after</h2><div class='card'><table class='ba'><thead><tr><th>Field</th>")
        for i in sample:
            h.append(f"<th>Row {run.result.rows[i]}: source</th><th>→ output</th>")
        h.append("</tr></thead><tbody>")
        for m in active:
            h.append(f"<tr><td><code>{e(m.field)}</code></td>")
            for i in sample:
                raw = run.table.rows[i][m.column]
                out = run.result.records[i][m.field]
                if not show_values and m.field not in _SAFE_FIELDS:
                    raw, out = mask(raw), mask(out)
                h.append(f"<td class='raw'>{e(raw)}</td><td>{e(out)}</td>")
            h.append("</tr>")
        h.append("</tbody></table></div>")

    if s["issues"]:
        h.append(
            "<h2>Issues found</h2><div class='card'><table><thead><tr><th>Code</th><th class='num'>Count</th></tr></thead><tbody>"
        )
        for k, v in sorted(s["issues"].items(), key=lambda kv: (-kv[1], kv[0])):
            h.append(f"<tr><td><code>{e(k)}</code></td><td class='num'>{v}</td></tr>")
        h.append("</tbody></table></div>")

    if run.review:
        shown = run.review[:60]
        h.append(
            f"<h2>Review queue · {len(run.review)} item(s)"
            + (f", first {len(shown)} shown" if len(shown) < len(run.review) else "")
            + "</h2>"
        )
        h.append(
            "<div class='card'><table><thead><tr><th>ID</th><th>Severity</th><th>Kind</th><th>Field</th><th class='num'>Row</th><th>Value</th><th>Problem</th><th>Suggestion</th></tr></thead><tbody>"
        )
        for r in shown:
            val = r.value if show_values or r.field in _SAFE_FIELDS else mask(r.value)
            val_html = f"<code>{e(val)}</code>" if val else ""
            h.append(
                f"<tr><td>{r.id}</td><td>{_pill(r.severity)}</td><td>{e(r.kind)}</td><td><code>{e(r.field or r.source)}</code></td>"
                f"<td class='num'>{r.row or ''}</td><td>{val_html}</td><td>{e(r.problem)}</td><td class='why'>{e(r.suggestion)}</td></tr>"
            )
        h.append("</tbody></table></div>")

    if run.result.ref_resolution:
        for fname, how in run.result.ref_resolution.items():
            h.append(
                f"<p class='meta'>{e(fname)} resolved by id: {how['id']}, by work email: {how['email']}, by name: {how['name']}.</p>"
            )
    h.append(
        f"<footer>{e(DISCLAIMER)}<br>Source sha256 <code>{e(t.sha256[:16])}…</code> · layout fingerprint <code>{e(t.fingerprint)}</code></footer>"
    )
    h.append("</main></body></html>\n")
    return "".join(h)


# Enum-like outputs and employment dates stay readable in a masked report.
_SAFE_FIELDS = {
    "employment_status",
    "employment_type",
    "pay_frequency",
    "salary_currency",
    "country",
    "fte",
    "start_date",
    "end_date",
}
