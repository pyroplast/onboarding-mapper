def _show(value: str, show: bool) -> str:
    return value if show else mask(value)


def report_md(run: Run, show_values: bool = False) -> str:
    s = run.stats()
    t = run.table
    out = [
        f"# Onboarding mapping report: {Path(t.source).name}",
        "",
        f"Schema `{run.schema.name}` v{run.schema.version} · as of {run.as_of.isoformat()} · onboarding-mapper {__version__}",
        "",
        "| Rows in | Ready | Held | Fields auto | To confirm | Unmapped | Review items |",
        "|---:|---:|---:|---:|---:|---:|---:|",
        f"| {s['rows_in']} | {s['records_ready']} | {s['records_held']} | {s['fields_auto']} | {s['fields_review']} | {s['fields_unmapped']} | {s['review_items']} |",
        "",
        "## Mapping",
        "",
        "| Target field | Source column | Status | Confidence | Why |",
        "|---|---|---|---:|---|",
    ]
    for m in run.mappings.values():
        src = (m.source or "—").replace("|", "\\|")
        if m.method != "direct":
            src += f" ({m.method.replace('_', ' ')})"
        why = "; ".join(m.reasons).replace("|", "\\|") or "—"
        conf = f"{m.confidence:.2f}" if m.source else ""
        out.append(f"| `{m.field}` | {src} | {m.status} | {conf} | {why} |")
    if run.proposal.sensitive:
        out += ["", "## Held back as sensitive", ""]
        out += [f"- **{h['source']}**: {h['label']} ({h['reason']})" for h in run.proposal.sensitive]
    if run.proposal.unused:
        out += ["", "## Columns not used", ""]
        out += [f"- {u['source']}: {u['reason']}" for u in run.proposal.unused]
    if s["issues"]:
        out += ["", "## Issues", "", "| Code | Count |", "|---|---:|"]
        out += [f"| `{k}` | {v} |" for k, v in sorted(s["issues"].items(), key=lambda kv: (-kv[1], kv[0]))]
    if run.review:
        out += [
            "",
            f"## Review queue (first {min(25, len(run.review))} of {len(run.review)})",
            "",
            "| ID | Severity | Field | Row | Value | Problem |",
            "|---|---|---|---:|---|---|",
        ]
        for r in run.review[:25]:
            val = _show(r.value, show_values).replace("|", "\\|")
            problem = r.problem.replace("|", "\\|")
            out.append(f"| {r.id} | {r.severity} | {r.field or r.source} | {r.row or ''} | `{val}` | {problem} |")
    out += ["", "---", "", DISCLAIMER, ""]
    return "\n".join(out)


