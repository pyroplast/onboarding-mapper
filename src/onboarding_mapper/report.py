_ANSI = {
    "auto": "32",
    "accepted": "32",
    "review": "33;1",
    "unmapped": "2",
    "rejected": "2",
    "error": "31;1",
    "warning": "33",
    "info": "36",
}


def to_text(run: Run, color: bool = False, timings: bool = True) -> str:
    def c(key: str, text: str) -> str:
        return f"\033[{_ANSI[key]}m{text}\033[0m" if color else text

    s = run.stats()
    t = run.table
    lines = [
        f"onboarding-mapper {__version__} · {Path(t.source).name} → schema '{run.schema.name}'",
        f"read {s['rows_in']} rows × {s['columns_in']} columns · {t.encoding}"
        + (f" · delimiter {t.delimiter!r}" if t.delimiter else "")
        + f" · header on row {t.header_row}",
    ]
    for note in t.notes:
        lines.append(f"  note: {note}")
    lines.append("")
    w = max(len(m.field) for m in run.mappings.values())
    for m in run.mappings.values():
        src = m.source or "—"
        if m.method == "split_full_name":
            src += f" (split, {m.options.get('part')} name)"
        elif m.method == "currency_from_amount":
            src += " (currency read from amounts)"
        conf = f"{m.confidence:.2f}" if m.source else "    "
        lines.append(f"  {m.field:<{w}}  {c(m.status, f'{m.status:<8}')} {conf}  {src}")
    if run.proposal.sensitive:
        lines.append("")
        for h in run.proposal.sensitive:
            lines.append(f"  held back: {h['source']} — {h['label']} ({h['reason']})")
    if run.proposal.unused:
        lines.append(f"  not used: {', '.join(u['source'] for u in run.proposal.unused)}")
    lines.append("")
    lines.append(
        f"records: {c('auto', str(s['records_ready']) + ' ready')} · {c('error', str(s['records_held']) + ' held')}"
        f" · {s['cells_normalised']} of {s['cells_mapped']} cells normalised"
    )
    lines.append(
        f"fields:  {s['fields_auto']} auto · {s['fields_review']} to confirm · {s['fields_unmapped']} unmapped"
    )
    lines.append(f"review queue: {s['review_items']} item(s) " + str(s["review_by_kind"]))
    if s["issues"]:
        lines.append(
            "issues:  " + ", ".join(f"{k} {v}" for k, v in sorted(s["issues"].items(), key=lambda kv: (-kv[1], kv[0])))
        )
    if timings:
        lines.append("time:    " + " · ".join(f"{k} {v:.0f} ms" for k, v in run.timings_ms.items()))
    return "\n".join(lines)


