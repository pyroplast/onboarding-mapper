"""Outputs of a run.

mapped.csv        records ready to import, in target-schema order
held.csv          records with at least one error, plus the reasons
review_queue.csv  everything a person has to decide, one line each
mapping.json      the mapping with confidences and reasons; edit it and re-run
report.json/.md/.html  the run in numbers, for the customer or the team

Only report.html and report.md are meant to be shared. They mask personal
values unless asked not to. Held-back sensitive columns are never read into
any output.
"""

from __future__ import annotations

import csv
import io
import json
from html import escape
from pathlib import Path

from . import __version__
from .engine import Run, mapping_to_dict
from .normalize import mask

DISCLAIMER = (
    "Generated by onboarding-mapper. Confidence scores are heuristic. Every mapping marked review, and every item "
    "in the review queue, needs a person's decision before import."
)


def _csv(rows: list[list[str]]) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerows(rows)
    return buf.getvalue()


def mapped_csv(run: Run) -> str:
    names = run.result.fields
    return _csv([names] + [[run.result.records[i][n] for n in names] for i in run.result.ready])


def held_csv(run: Run) -> str:
    names = run.result.fields
    errs = run.result.errors_by_record()
    rows = [["_source_row", "_errors"] + names]
    for i in run.result.held:
        reasons = "; ".join(f"{e.field}: {e.message}" for e in errs[i])
        rows.append([str(run.result.rows[i]), reasons] + [run.result.records[i][n] for n in names])
    return _csv(rows)


def review_csv(run: Run) -> str:
    cols = ["id", "kind", "severity", "code", "field", "source", "row", "value", "problem", "suggestion", "decision"]
    rows = [cols]
    for item in run.review:
        d = item.to_dict()
        rows.append([str(d[c]) for c in cols[:-1]] + [""])
    return _csv(rows)


def summary(run: Run) -> dict:
    s = run.stats()
    return {
        "tool": "onboarding-mapper",
        "version": __version__,
        "as_of": run.as_of.isoformat(),
        "schema": {"name": run.schema.name, "version": run.schema.version},
        "source": {
            "file": Path(run.table.source).name,
            "sha256": run.table.sha256,
            "fingerprint": run.table.fingerprint,
            "encoding": run.table.encoding,
            "delimiter": run.table.delimiter,
            "header_row": run.table.header_row,
            "notes": run.table.notes,
        },
        "mapping_source": "proposed" if run.mapping_source == "proposed" else "mapping file",
        "stats": s,
        "manager_resolution": run.result.ref_resolution,
        "disclaimer": DISCLAIMER,
    }


def report_json(run: Run) -> str:
    payload = summary(run)
    payload["mapping"] = [m.to_dict() for m in run.mappings.values()]
    payload["held_back"] = run.proposal.sensitive
    payload["unused"] = run.proposal.unused
    payload["profiles"] = [p.to_dict() for p in run.profiles]
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def write_all(run: Run, out: str | Path, show_values: bool = False) -> dict[str, Path]:
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "mapped.csv": mapped_csv(run),
        "held.csv": held_csv(run),
        "review_queue.csv": review_csv(run),
        "mapping.json": json.dumps(mapping_to_dict(run), indent=2, ensure_ascii=False) + "\n",
        "report.json": report_json(run),
        "report.md": report_md(run, show_values),
        "report.html": report_html(run, show_values),
    }
    paths = {}
    for name, text in files.items():
        path = out / name
        path.write_text(text, encoding="utf-8", newline="")
        paths[name] = path
    return paths


