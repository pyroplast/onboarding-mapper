    _seen: dict[str, float] = {}
    for _item in _items:
        _phrase, _weight = (_item, 1.0) if isinstance(_item, str) else _item
        _key = norm_header(_phrase)
        _seen[_key] = max(_seen.get(_key, 0.0), _weight)
    ALIASES[_concept] = sorted(_seen.items())

