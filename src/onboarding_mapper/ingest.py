"""Read a customer export the way it actually arrives.

Handles: UTF-8 with or without BOM, UTF-16, Windows-1252/Latin-1; comma,
semicolon, tab and pipe delimiters; title rows and blank rows above the header;
blank and duplicate column names; trailing "Total"/"Generated by" rows; ragged
rows; and .xlsx workbooks (first sheet, read with the standard library only).
"""

from __future__ import annotations

import csv
import hashlib
import io
import re
import zipfile
from dataclasses import dataclass, field
from pathlib import Path
from xml.etree import ElementTree

from .normalize import clean_cell, norm_text

MAX_BYTES = 200 * 1024 * 1024
_DELIMITERS = [",", ";", "\t", "|"]
_FOOTER = re.compile(
    r"^(?:total|totals|sum|summe|gesamt|suma|totales|generated|exported|report generated|page \d+|fin del informe|end of report|\d+ (?:rows|records|registros|datensatze|employees|empleados))\b"
)


class IngestError(ValueError):
    pass


@dataclass
class Table:
    source: str
    headers: list[str]
    rows: list[list[str]]
    row_numbers: list[int]  # 1-based line/row number in the source, for pointing people at the cell
    encoding: str = ""
    delimiter: str = ""
    header_row: int = 1
    notes: list[str] = field(default_factory=list)
    sha256: str = ""

    def column(self, index: int) -> list[str]:
        return [row[index] for row in self.rows]

    @property
    def fingerprint(self) -> str:
        """Identifies the export's layout (not its contents): same headers, same fingerprint."""
        return hashlib.sha256("\x1f".join(self.headers).encode("utf-8")).hexdigest()[:16]


# ---------------------------------------------------------------------------
# Decoding
# ---------------------------------------------------------------------------


def _decode(data: bytes) -> tuple[str, str]:
    if data.startswith(b"\xef\xbb\xbf"):
        return data[3:].decode("utf-8", "replace"), "utf-8-sig"
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return data.decode("utf-16", "replace"), "utf-16"
    try:
        return data.decode("utf-8"), "utf-8"
    except UnicodeDecodeError:
        pass
    text = data.decode("cp1252", "replace")
    return text, "cp1252"


def _sniff_delimiter(lines: list[str]) -> str:
    """Pick the delimiter that splits the sample into the most consistent, widest rows."""
    best, best_score = ",", -1.0
    sample = [ln for ln in lines if ln.strip()][:40]
    for delim in _DELIMITERS:
        try:
            widths = [len(r) for r in csv.reader(sample, delimiter=delim)]
        except csv.Error:
            continue
        if not widths:
            continue
        common = max(set(widths), key=lambda w: (widths.count(w), w))
        if common < 2:
            continue
        score = widths.count(common) / len(widths) * common
        if score > best_score:
            best, best_score = delim, score
    return best


# ---------------------------------------------------------------------------
# Header detection
# ---------------------------------------------------------------------------

_NUMERICISH = re.compile(r"^[\d\s.,:/+\-€$£%]+$")


def _header_score(row: list[str], width: int) -> float:
    cells = [clean_cell(c) for c in row]
    filled = [c for c in cells if c]
    if len(filled) < max(2, int(width * 0.5)):
        return 0.0
    texty = sum(1 for c in filled if not _NUMERICISH.match(c) and "@" not in c and len(c) <= 60)
    distinct = len({c.lower() for c in filled})
    return (texty / len(filled)) * (distinct / len(filled)) * (len(filled) / width)


def _find_header(rows: list[list[str]]) -> int:
    width = max((len(r) for r in rows[:60]), default=0)
    best, best_score = 0, 0.0
    for i, row in enumerate(rows[:15]):
        score = _header_score(row, width)
        # A header should be followed by rows of about the same width.
        follow = rows[i + 1 : i + 6]
        if follow and sum(1 for r in follow if sum(1 for c in r if clean_cell(c)) >= 2) < max(1, len(follow) // 2):
            score *= 0.5
        if score > best_score + 0.05:
            best, best_score = i, score
    return best


def _dedupe(headers: list[str]) -> list[str]:
    out: list[str] = []
    seen: dict[str, int] = {}
    for i, h in enumerate(headers):
        name = clean_cell(h) or f"column_{i + 1}"
        key = name.lower()
        if key in seen:
            seen[key] += 1
            name = f"{name} ({seen[key]})"
        else:
            seen[key] = 1
        out.append(name)
    return out


def _is_footer(row: list[str]) -> bool:
    filled = [clean_cell(c) for c in row if clean_cell(c)]
    if not filled:
        return False
    return len(filled) <= 3 and bool(_FOOTER.match(norm_text(filled[0])))


def _build(
    source: str, raw_rows: list[list[str]], sha: str, encoding: str, delimiter: str, line_numbers: list[int]
) -> Table:
    if not raw_rows:
        raise IngestError("the file has no rows")
    h = _find_header(raw_rows)
    notes: list[str] = []
    if h:
        notes.append(f"skipped {h} row(s) above the header")
    width = max(len(r) for r in raw_rows[h:])
    header = list(raw_rows[h]) + [""] * (width - len(raw_rows[h]))

    body: list[list[str]] = []
    numbers: list[int] = []
    ragged = 0
    footers = 0
    for row, n in zip(raw_rows[h + 1 :], line_numbers[h + 1 :]):
        if not any(clean_cell(c) for c in row):
            continue
        if _is_footer(row):
            footers += 1
            continue
        if len(row) != width:
            ragged += 1
            row = (list(row) + [""] * width)[:width]
        body.append([clean_cell(c) for c in row])
        numbers.append(n)

    # Drop columns that have neither a header nor any value.
    keep = [i for i in range(width) if clean_cell(header[i]) or any(r[i] for r in body)]
    if len(keep) < width:
        notes.append(f"dropped {width - len(keep)} empty column(s)")
    header = [header[i] for i in keep]
    body = [[r[i] for i in keep] for r in body]
    if ragged:
        notes.append(f"{ragged} row(s) had a different number of cells than the header and were padded or cut")
    if footers:
        notes.append(f"skipped {footers} footer/total row(s)")
    if not body:
        raise IngestError("found a header but no data rows")
    return Table(source, _dedupe(header), body, numbers, encoding, delimiter, line_numbers[h], notes, sha)


# ---------------------------------------------------------------------------
# CSV / TXT
# ---------------------------------------------------------------------------


def read_csv_bytes(data: bytes, source: str = "<bytes>") -> Table:
    sha = hashlib.sha256(data).hexdigest()
    text, encoding = _decode(data)
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    delimiter = _sniff_delimiter(lines)
    rows: list[list[str]] = []
    numbers: list[int] = []
    reader = csv.reader(io.StringIO(text), delimiter=delimiter)
    try:
        for row in reader:
            rows.append(row)
            numbers.append(reader.line_num)
    except csv.Error as exc:
        raise IngestError(f"cannot parse as delimited text: {exc}") from exc
    table = _build(source, rows, sha, encoding, delimiter, numbers)
    if encoding == "cp1252":
        table.notes.insert(0, "file is not UTF-8; read as Windows-1252")
    return table


# ---------------------------------------------------------------------------
# XLSX (first worksheet), standard library only
# ---------------------------------------------------------------------------

_NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
_REL_NS = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
_COL = re.compile(r"([A-Z]+)")


def _col_index(ref: str) -> int:
    letters = _COL.match(ref).group(1)  # type: ignore[union-attr]
    n = 0
    for ch in letters:
        n = n * 26 + (ord(ch) - 64)
    return n - 1


def read_xlsx_bytes(data: bytes, source: str = "<bytes>") -> Table:
    sha = hashlib.sha256(data).hexdigest()
    try:
        z = zipfile.ZipFile(io.BytesIO(data))
    except zipfile.BadZipFile as exc:
        raise IngestError("not a valid .xlsx file") from exc
    with z:
        names = set(z.namelist())
        shared: list[str] = []
        if "xl/sharedStrings.xml" in names:
            root = ElementTree.fromstring(z.read("xl/sharedStrings.xml"))
            for si in root.findall("m:si", _NS):
                shared.append("".join(t.text or "" for t in si.iter(f"{{{_NS['m']}}}t")))
        date_styles = _date_styles(z, names)
        sheet = _first_sheet(z, names)
        root = ElementTree.fromstring(z.read(sheet))
    rows: list[list[str]] = []
    numbers: list[int] = []
    for row in root.iter(f"{{{_NS['m']}}}row"):
        cells: dict[int, str] = {}
        for c in row.findall("m:c", _NS):
            ref = c.get("r", "")
            idx = _col_index(ref) if ref else len(cells)
            ctype = c.get("t", "")
            v = c.find("m:v", _NS)
            if ctype == "s" and v is not None:
                value = shared[int(v.text or 0)]
            elif ctype == "inlineStr":
                value = "".join(t.text or "" for t in c.iter(f"{{{_NS['m']}}}t"))
            elif v is not None:
                value = v.text or ""
                if c.get("s") and int(c.get("s", "0")) in date_styles and re.match(r"^\d+(\.\d+)?$", value):
                    from datetime import date, timedelta

                    value = (date(1899, 12, 30) + timedelta(days=int(float(value)))).isoformat()
                elif re.match(r"^-?\d+\.0$", value):
                    value = value[:-2]
            else:
                value = ""
            cells[idx] = value
        width = max(cells) + 1 if cells else 0
        rows.append([cells.get(i, "") for i in range(width)])
        numbers.append(int(row.get("r", len(rows))))
    return _build(source, rows, sha, "xlsx", "", numbers)


def _first_sheet(z: zipfile.ZipFile, names: set[str]) -> str:
    try:
        wb = ElementTree.fromstring(z.read("xl/workbook.xml"))
        first = wb.find("m:sheets/m:sheet", _NS)
        rid = first.get(_REL_NS) if first is not None else None
        rels = ElementTree.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        for rel in rels:
            if rel.get("Id") == rid:
                target = rel.get("Target", "").lstrip("/")
                return target if target.startswith("xl/") else "xl/" + target
    except (KeyError, ElementTree.ParseError):
        pass
    sheets = sorted(n for n in names if n.startswith("xl/worksheets/sheet"))
    if not sheets:
        raise IngestError("workbook has no worksheets")
    return sheets[0]


_BUILTIN_DATE_FORMATS = {14, 15, 16, 17, 22, 27, 30, 36, 45, 46, 47, 50, 57}


def _date_styles(z: zipfile.ZipFile, names: set[str]) -> set[int]:
    if "xl/styles.xml" not in names:
        return set()
    root = ElementTree.fromstring(z.read("xl/styles.xml"))
    custom = {}
    for fmt in root.findall("m:numFmts/m:numFmt", _NS):
        code = (fmt.get("formatCode") or "").lower()
        code = re.sub(r'"[^"]*"|\[[^\]]*\]', "", code)
        custom[int(fmt.get("numFmtId", "0"))] = any(ch in code for ch in "dy") and "h" not in code
    out = set()
    xfs = root.find("m:cellXfs", _NS)
    for i, xf in enumerate(xfs if xfs is not None else []):
        fid = int(xf.get("numFmtId", "0"))
        if fid in _BUILTIN_DATE_FORMATS or custom.get(fid):
            out.add(i)
    return out


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------


def read(path: str | Path) -> Table:
    path = Path(path)
    try:
        size = path.stat().st_size
    except OSError as exc:
        raise IngestError(f"cannot read {path}: {exc.strerror}") from exc
    if size > MAX_BYTES:
        raise IngestError(f"file is larger than {MAX_BYTES // (1024 * 1024)} MB")
    data = path.read_bytes()
    if not data.strip():
        raise IngestError("file is empty")
    if path.suffix.lower() in {".xlsx", ".xlsm"} or data[:4] == b"PK\x03\x04":
        return read_xlsx_bytes(data, str(path))
    return read_csv_bytes(data, str(path))
